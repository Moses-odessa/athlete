/// Единица измерения результата теста. Определяет формат ввода и валидацию
/// (ТЗ разд. 4.5), а также способ расчёта балла.
enum MeasurementUnit {
  /// Время в секундах (для «меньше — лучше»: бег, реакция).
  seconds,

  /// Дистанция в метрах (тест Купера, бросок медбола).
  meters,

  /// Дистанция/высота в сантиметрах (прыжки, наклон вперёд).
  centimeters,

  /// Абсолютный вес в килограммах.
  kilograms,

  /// Количество повторений.
  reps,

  /// Норматив задан как множитель массы тела (BW), результат вводится в кг.
  bodyweightMultiple,

  /// Качественная экспертная оценка 1–5 (ТЗ разд. 5.5).
  qualitative1to5,
}
